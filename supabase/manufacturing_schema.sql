-- NOVA MANUFACTURING — 15 bảng dữ liệu sản xuất giả lập (PostgreSQL / Supabase)
-- Chạy trong SQL Editor của Supabase. Sau đó chạy: npm run manufacturing:load
-- Các bảng nằm trong schema public, không trùng tên với bảng nội dung của website.

-- ============================================================
-- A. Master Data – Dữ liệu nền
-- ============================================================

create table if not exists departments (
  department_id    bigint generated by default as identity primary key,
  department_code  varchar(20) not null unique,
  department_name  varchar(100) not null
);

create table if not exists shifts (
  shift_id    bigint generated by default as identity primary key,
  shift_name  varchar(30) not null unique,
  start_hour  int not null check (start_hour between 0 and 23),
  end_hour    int not null check (end_hour between 0 and 23)
);

create table if not exists employees (
  employee_id    bigint generated by default as identity primary key,
  department_id  bigint not null references departments(department_id),
  shift_id       bigint references shifts(shift_id),
  full_name      varchar(120) not null,
  role           varchar(20) not null check (role in ('Operator', 'Supervisor', 'Engineer', 'Inspector')),
  hire_date      date not null
);

create table if not exists production_lines (
  line_id        bigint generated by default as identity primary key,
  line_code      varchar(20) not null unique,
  line_name      varchar(100) not null,
  department_id  bigint not null references departments(department_id),
  location       varchar(60)
);

create table if not exists machines (
  machine_id       bigint generated by default as identity primary key,
  machine_code     varchar(20) not null unique,
  machine_name     varchar(100) not null,
  line_id          bigint not null references production_lines(line_id),
  machine_type     varchar(40),
  ideal_cycle_sec  numeric(8, 2) not null check (ideal_cycle_sec > 0)
);

create table if not exists products (
  product_id        bigint generated by default as identity primary key,
  product_code     varchar(20) not null unique,
  product_name     varchar(100) not null,
  product_family   varchar(40),
  standard_cycle_sec numeric(8, 2) not null check (standard_cycle_sec > 0)
);

-- ============================================================
-- B. Production – Sản xuất
-- ============================================================

create table if not exists production_orders (
  order_id     bigint generated by default as identity primary key,
  order_code   varchar(30) not null unique,
  product_id   bigint not null references products(product_id),
  line_id      bigint not null references production_lines(line_id),
  planned_qty  int not null check (planned_qty > 0),
  start_time   timestamp not null,
  end_time     timestamp,
  status       varchar(20) not null check (status in ('Planned', 'Running', 'Completed', 'Cancelled')),
  check (end_time is null or end_time >= start_time)
);

create table if not exists production_records (
  record_id    bigint generated by default as identity primary key,
  order_id     bigint not null references production_orders(order_id),
  machine_id   bigint not null references machines(machine_id),
  shift_id     bigint not null references shifts(shift_id),
  operator_id  bigint references employees(employee_id),
  record_time  timestamp not null,
  good_qty     int not null check (good_qty >= 0),
  ng_qty       int not null check (ng_qty >= 0),
  total_qty    int not null check (total_qty = good_qty + ng_qty)
);

create table if not exists machine_cycles (
  cycle_id        bigint generated by default as identity primary key,
  machine_id      bigint not null references machines(machine_id),
  order_id        bigint not null references production_orders(order_id),
  cycle_start     timestamp not null,
  cycle_time_sec  numeric(8, 2) not null check (cycle_time_sec > 0)
);

-- ============================================================
-- C. Quality – Chất lượng
-- ============================================================

create table if not exists defect_types (
  defect_type_id  bigint generated by default as identity primary key,
  defect_code     varchar(20) not null unique,
  defect_name     varchar(100) not null,
  severity        varchar(10) not null check (severity in ('Minor', 'Major', 'Critical'))
);

create table if not exists quality_inspections (
  inspection_id   bigint generated by default as identity primary key,
  order_id        bigint not null references production_orders(order_id),
  defect_type_id  bigint references defect_types(defect_type_id),
  inspector_id    bigint references employees(employee_id),
  inspected_at    timestamp not null,
  sample_qty      int not null check (sample_qty > 0),
  defect_qty      int not null check (defect_qty >= 0 and defect_qty <= sample_qty),
  result          varchar(5) not null check (result in ('OK', 'NG'))
);

-- ============================================================
-- D. Downtime – Dừng máy
-- ============================================================

create table if not exists downtime_reasons (
  reason_id    bigint generated by default as identity primary key,
  reason_code  varchar(20) not null unique,
  reason_name  varchar(100) not null,
  category     varchar(30) not null check (category in ('Planned', 'Breakdown', 'Changeover', 'Material', 'Quality', 'Other'))
);

create table if not exists downtime_events (
  downtime_id       bigint generated by default as identity primary key,
  machine_id        bigint not null references machines(machine_id),
  order_id          bigint references production_orders(order_id),
  reason_id         bigint not null references downtime_reasons(reason_id),
  start_time        timestamp not null,
  end_time         timestamp not null,
  duration_minutes  numeric(8, 2) not null check (duration_minutes >= 0),
  check (end_time >= start_time)
);

-- ============================================================
-- E. Material – Nguyên vật liệu
-- ============================================================

create table if not exists materials (
  material_id    bigint generated by default as identity primary key,
  material_code  varchar(20) not null unique,
  material_name  varchar(100) not null,
  unit           varchar(10) not null,
  unit_cost      numeric(12, 2) not null check (unit_cost >= 0)
);

create table if not exists material_transactions (
  txn_id       bigint generated by default as identity primary key,
  material_id  bigint not null references materials(material_id),
  order_id     bigint references production_orders(order_id),
  txn_type     varchar(5) not null check (txn_type in ('IN', 'OUT', 'USE')),
  qty          numeric(12, 2) not null check (qty > 0),
  txn_time     timestamp not null
);

-- ============================================================
-- Index cho các truy vấn theo thời gian và khóa ngoại
-- ============================================================

create index if not exists idx_orders_line_start on production_orders(line_id, start_time);
create index if not exists idx_records_order on production_records(order_id);
create index if not exists idx_records_machine_time on production_records(machine_id, record_time);
create index if not exists idx_records_shift on production_records(shift_id);
create index if not exists idx_cycles_machine_time on machine_cycles(machine_id, cycle_start);
create index if not exists idx_inspections_order on quality_inspections(order_id);
create index if not exists idx_downtime_machine_time on downtime_events(machine_id, start_time);
create index if not exists idx_downtime_reason on downtime_events(reason_id);
create index if not exists idx_material_txn_material on material_transactions(material_id, txn_time);

